// A lightweight, dependency-free translation system.
//
// Why not a library like i18next? Given everything already involved in
// getting this project running, we're deliberately keeping this simple:
// one plain object, one lookup function, nothing to configure or that
// can fail to load. Adding a new language later means adding one new
// block below — nothing else in the app needs to change.
//
// Coverage note: English, Hindi, Marathi, Tamil, Telugu, and Bengali are
// fully translated here (together, the first languages of well over half
// of India). More languages can be added the same way — each one is a
// self-contained block, so this is a starting set, not a ceiling.

